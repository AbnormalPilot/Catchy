import AppKit

/// Polls the general pasteboard (there is no change notification on macOS) and reports
/// copies that look like an event. Text copied on an iPhone arrives here too, via
/// Universal Clipboard.
///
/// It asks the system's privacy-preserving detector first. Longer text is only read when that
/// detector finds an event; chat-length text is also checked on-device for "in 20 mins"-style
/// times, which the system detector misses. Nothing is stored or sent anywhere.
final class ClipboardWatcher {
    var onEventText: (String, CaptureSource) -> Void = { _, _ in }
    /// Auto-catching off ("Pause Catching" in the menu). Manual catching still works.
    var isPaused: () -> Bool = { false }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var lastText: String?
    private var timer: Timer?

    /// Password managers mark secrets with these (see nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard !isPaused(), types.isDisjoint(with: Self.ignoredTypes) else { return }

        // A picture (a copied screenshot, or a photo copied on the iPhone). Copied files also
        // carry an icon image, so skip anything that is a file.
        if !types.contains(.string), !types.contains(.fileURL), !types.isDisjoint(with: Self.imageTypes) {
            catchImage(changeCount: lastChangeCount)
            return
        }
        guard types.contains(.string) else { return }

        let changeCount = lastChangeCount
        Task {
            let systemSeesEvent = await Self.containsEvent()
            guard changeCount == pasteboard.changeCount,
                  let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
                  (4...5000).contains(text.count),
                  text != lastText,
                  // macOS misses "meet with Sujan in 20 mins"; chat-length text gets a local check for that.
                  systemSeesEvent || (text.count <= 280 && DateHints.relativeTimes(in: text, now: .now).start != nil)
            else { return }
            lastText = text
            onEventText(text, .clipboard)
        }
    }

    private static let imageTypes: Set<NSPasteboard.PasteboardType> = [
        .png, .tiff, .init("public.jpeg"), .init("public.heic"),
    ]

    private func catchImage(changeCount: Int) {
        guard let image = NSImage(pasteboard: pasteboard),
              let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
        Task {
            guard let text = try? await ScreenReader.recognizeText(in: cgImage),
                  changeCount == pasteboard.changeCount,
                  !DateHints(text: text).dates.isEmpty
            else { return }
            lastText = text
            onEventText(text, .image)
        }
    }

    /// Runs off the main actor: the system detector doesn't expose the contents to us.
    nonisolated private static func containsEvent() async -> Bool {
        let patterns = try? await NSPasteboard.general.detectedPatterns(for: [\.calendarEvents])
        return patterns?.contains(\.calendarEvents) ?? false
    }
}
